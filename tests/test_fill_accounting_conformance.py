"""Conformance of OrderState.apply_fill_accounting to the ImandraX model `step_fixed`.

Each case is one region of the model's decomposition (subject "order fill accounting");
the vectors were generated by ImandraX. The adapter maps model values onto the code:

* model ``state.f_cum``  -> ``OrderState.cum_qty``
* model ``state.fills``  -> ``OrderState.fills`` (ExecID -> (LastQty, LastPx))
* model ``report``       -> an ``ExecutionReport`` parsed from a FIX message:
  trans TNew/TBust/TCorrect -> ExecTransType 0/1/2; kind KFill/KOther -> ExecType 1/0
* prices are integers in millionths of a dollar in the model, Decimals in the code.
"""

import json
from decimal import Decimal
from pathlib import Path

import pytest

from nyse_pillar_fix import tags as T
from nyse_pillar_fix.client import OrderState
from nyse_pillar_fix.codec import Message
from nyse_pillar_fix.messages import ExecutionReport, NewOrderSingle, Routing

VECTORS = json.loads((Path(__file__).parent / "vectors" / "fill_accounting_regions.json").read_text())["cases"]
TRANS = {"TNew": "0", "TBust": "1", "TCorrect": "2"}
KIND = {"KFill": "1", "KOther": "0"}


def px(micros: int) -> Decimal:
    return Decimal(micros).scaleb(-6)


def to_state(s: dict) -> OrderState:
    req = NewOrderSingle(cl_ord_id="O1", symbol="IBM", side="1", order_qty=100, price="1", routing=Routing(mpid="X"))
    state = OrderState(request=req, cl_ord_id="O1", cum_qty=s["f_cum"])
    for f in reversed(s["fills"]):
        state.fills[str(f["fid"])] = (f["fqty"], px(f["fpx"]))
    return state


def to_report(r: dict) -> ExecutionReport:
    fields = [
        (T.ClOrdID, "O1"),
        (T.ExecTransType, TRANS[r["trans"]]),
        (T.ExecType, KIND[r["kind"]]),
        (T.OrdStatus, KIND[r["kind"]]),
        (T.ExecID, r["exec_id"]),
        (T.ExecRefID, r["ref_id"]),
        (T.LastQty, r["last_qty"]),
        (T.LastPx, px(r["last_px"])),
    ]
    if r["cum_qty"] is not None:
        fields.append((T.CumQty, r["cum_qty"]))
    return ExecutionReport.from_message(Message("8", fields))


@pytest.mark.parametrize("case", VECTORS, ids=[c["name"] for c in VECTORS])
def test_region(case):
    state = to_state(case["input"]["s"])
    state.apply_fill_accounting(to_report(case["input"]["r"]))
    expected = to_state(case["expected"])
    assert state.cum_qty == expected.cum_qty
    assert state.fills == expected.fills
